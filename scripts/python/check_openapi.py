#!/usr/bin/env python
"""Assert the generated OpenAPI surface matches the P1 + P2 + P3 contract exactly.

Used by ``scripts/powershell/test_all.ps1`` and by CI as a cheap, offline
contract gate. It imports the FastAPI app (no server, no network) and checks:

1. the **exact** path set — P1's two public paths, the P2 allowlist and the P3
   document allowlist, with no extra path tolerated (an unplanned route, a P4+
   route, a stray ``/demo/seed`` or a premature ``/demo/status`` all fail);
2. the **exact** HTTP method set per path (``/patient/check-ins`` legitimately
   carries ``GET`` + ``POST``, so paths alone are not enough);
3. the P1 schemas (``Health``, ``VersionInfo``, ``DependencyState``) are
   unchanged — the Phase 1 assertions are retained, not relaxed;
4. the P2 and P3 schema allowlists are exactly present — a schema appearing only
   because a later-phase model leaked into the app still fails;
5. per-operation ``security``: only ``/health``, ``/version`` and ``login`` are
   public, everything else requires ``bearerAuth``;
6. the contract's ``bearerAuth`` scheme (``scheme``, ``bearerFormat``) and the
   educational notice are present.

Exit code 0 = contract matches, 1 = mismatch (details on stderr).

EDUCATIONAL / SYNTHETIC DATA / NOT FOR CLINICAL USE
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "backend"))

#: Phase 1 surface. Kept as an equality assertion: P1 must not lose a route.
P1_PATHS: dict[str, set[str]] = {
    "/health": {"get"},
    "/version": {"get"},
}

#: Phase 2 allowlist, one entry per operation-bearing path.
#:
#: 9 unique paths / 10 operations for P2; with P1 that is 11 paths / 12
#: operations. ``GET /api/v1/demo/status`` is deliberately absent (``OQ-P2-01``,
#: deferred to P5) and ``POST /api/v1/demo/seed`` does not exist in any phase.
P2_PATHS: dict[str, set[str]] = {
    "/api/v1/auth/login": {"post"},
    "/api/v1/auth/me": {"get"},
    "/api/v1/auth/logout": {"post"},
    "/api/v1/doctor/patients": {"get"},
    "/api/v1/doctor/patients/{patient_id}": {"get"},
    "/api/v1/doctor/patients/{patient_id}/timeline": {"get"},
    "/api/v1/doctor/patients/{patient_id}/observations": {"get"},
    "/api/v1/patient/check-ins": {"get", "post"},
    "/api/v1/demo/reset": {"post"},
}

#: Phase 3 document allowlist: 6 paths / 6 operations. Every route is reachable
#: only through ``app.api.v1.documents``; the shapes are fixed by
#: ``API_CONTRACT.md`` §2.4 and there is no P3 route outside this set.
P3_PATHS: dict[str, set[str]] = {
    "/api/v1/documents/upload": {"post"},
    "/api/v1/documents/{document_id}": {"get"},
    "/api/v1/documents/{document_id}/extraction": {"get"},
    "/api/v1/documents/{document_id}/text": {"get"},
    "/api/v1/documents/{document_id}/verify": {"post"},
    "/api/v1/documents/{document_id}/file": {"get"},
}

EXPECTED_PATHS: dict[str, set[str]] = {**P1_PATHS, **P2_PATHS, **P3_PATHS}

#: Operations that must stay public (``security: []``).
PUBLIC_OPERATIONS: set[tuple[str, str]] = {
    ("/health", "get"),
    ("/version", "get"),
    ("/api/v1/auth/login", "post"),
}

EXPECTED_HEALTH_REQUIRED = {"status", "version", "db", "ollama", "tesseract"}
EXPECTED_VERSION_REQUIRED = {
    "app_version",
    "api_version",
    "workflow_version",
    "policy_version",
}
EXPECTED_DEPENDENCY_ENUM = ["ok", "unavailable", "not_configured"]
EXPECTED_NOTICE = "EDUCATIONAL / SYNTHETIC DATA / NOT FOR CLINICAL USE"
EXPECTED_BEARER_FORMAT = "opaque-session-token"

#: Every component schema a P1 + P2 document may contain. Equality, not superset:
#: a schema that appears only because a P3+ model leaked into the app fails here.
EXPECTED_SCHEMAS: set[str] = {
    # P1
    "Health",
    "VersionInfo",
    "DependencyState",
    # generated by FastAPI itself
    "HTTPValidationError",
    "ValidationError",
    # P2 — auth
    "LoginRequest",
    "TokenResponse",
    "UserRead",
    # P2 — patient domain
    "CheckInCreate",
    "DemoResetResponse",
    "ObservationList",
    "ObservationRead",
    "ObservationVerification",
    "PatientList",
    "PatientRead",
    "Timeline",
    # P2 — shared enums surfaced in responses
    "MeasureType",
    "ObservationSource",
    "Role",
    "TrustLevel",
    "Unit",
    "ValidationState",
    # P3 — documents (``API_CONTRACT.md`` §3)
    "DocumentMeta",
    "DocumentPageTextItem",
    "DocumentTextResponse",
    "DocumentUploadResponse",
    "EvidenceRef",
    "ExtractedFact",
    "ExtractionAttemptSummary",
    "ExtractionResponse",
    "VerificationIssue",
    "VerificationRecord",
    "VerifyRequest",
    "VerifyResponse",
    # P3 — shared enums surfaced in document responses
    "DocumentMimeType",
    "DocumentStatus",
    "ExtractionPath",
    "FactField",
    "FactVerificationStatus",
    "IssueType",
    "QualityFlag",
    "VerificationDecision",
    # P3 — the multipart request body FastAPI generates for the upload route.
    # It is structural, not a contract schema: the contract models the upload as
    # ``multipart/form-data`` inline, so this single generated name is allowed
    # explicitly rather than by a wildcard.
    "Body_upload_document_api_v1_documents_upload_post",
}

_HTTP_METHODS = {"get", "put", "post", "delete", "options", "head", "patch", "trace"}


def _operations(schema: dict[str, Any]) -> dict[str, set[str]]:
    """Return ``{path: {methods}}`` for every operation in the document."""
    found: dict[str, set[str]] = {}
    for path, item in schema.get("paths", {}).items():
        methods = {method.lower() for method in item if method.lower() in _HTTP_METHODS}
        if methods:
            found[path] = methods
    return found


def collect_errors(schema: dict[str, Any]) -> list[str]:
    """Return every contract deviation found in ``schema`` (empty = conforming)."""
    errors: list[str] = []

    found = _operations(schema)
    expected_paths = set(EXPECTED_PATHS)
    found_paths = set(found)

    missing = expected_paths - found_paths
    if missing:
        errors.append(f"missing expected paths: {sorted(missing)}")

    unexpected = found_paths - expected_paths
    if unexpected:
        errors.append(f"unexpected paths (not in the P1+P2+P3 allowlist): {sorted(unexpected)}")

    for path in sorted(expected_paths & found_paths):
        if found[path] != EXPECTED_PATHS[path]:
            errors.append(
                f"{path} methods mismatch: expected {sorted(EXPECTED_PATHS[path])}, "
                f"found {sorted(found[path])}"
            )

    components = schema.get("components", {}).get("schemas", {})
    missing_schemas = EXPECTED_SCHEMAS - set(components)
    if missing_schemas:
        errors.append(f"missing component schemas: {sorted(missing_schemas)}")
    unexpected_schemas = set(components) - EXPECTED_SCHEMAS
    if unexpected_schemas:
        errors.append(f"unexpected component schemas: {sorted(unexpected_schemas)}")

    # --- P1 regression assertions (unchanged from the Phase 1 gate) ---------
    health = components.get("Health")
    if not health:
        errors.append("components.schemas.Health is missing")
    else:
        required = set(health.get("required", []))
        if required != EXPECTED_HEALTH_REQUIRED:
            errors.append(
                f"Health.required mismatch: expected {sorted(EXPECTED_HEALTH_REQUIRED)}, "
                f"found {sorted(required)}"
            )
        status_enum = health.get("properties", {}).get("status", {}).get("enum")
        if status_enum != ["ok", "degraded"]:
            errors.append(f"Health.status enum mismatch: {status_enum!r}")

    dependency = components.get("DependencyState")
    if not dependency:
        errors.append("components.schemas.DependencyState is missing")
    elif dependency.get("enum") != EXPECTED_DEPENDENCY_ENUM:
        errors.append(f"DependencyState enum mismatch: {dependency.get('enum')!r}")

    version = components.get("VersionInfo")
    if not version:
        errors.append("components.schemas.VersionInfo is missing")
    else:
        required = set(version.get("required", []))
        if required != EXPECTED_VERSION_REQUIRED:
            errors.append(
                f"VersionInfo.required mismatch: expected {sorted(EXPECTED_VERSION_REQUIRED)}, "
                f"found {sorted(required)}"
            )
        if version.get("properties", {}).get("api_version", {}).get("const") != "v1":
            errors.append("VersionInfo.api_version must be const 'v1'")

    # --- per-operation security --------------------------------------------
    for path, methods in EXPECTED_PATHS.items():
        for method in methods:
            operation = schema.get("paths", {}).get(path, {}).get(method)
            if operation is None:
                continue
            declared = operation.get("security")
            if (path, method) in PUBLIC_OPERATIONS:
                if declared != []:
                    errors.append(f"{method.upper()} {path} must declare security: [] (public)")
            elif declared != [{"bearerAuth": []}]:
                errors.append(
                    f"{method.upper()} {path} must require bearerAuth, found {declared!r}"
                )

    # --- scheme + notice ----------------------------------------------------
    schemes = schema.get("components", {}).get("securitySchemes", {})
    bearer = schemes.get("bearerAuth")
    if not bearer:
        errors.append("components.securitySchemes.bearerAuth is missing")
    else:
        if bearer.get("type") != "http" or bearer.get("scheme") != "bearer":
            errors.append(f"bearerAuth must be an HTTP bearer scheme, found {bearer!r}")
        if bearer.get("bearerFormat") != EXPECTED_BEARER_FORMAT:
            errors.append(
                f"bearerAuth.bearerFormat must be {EXPECTED_BEARER_FORMAT!r}, "
                f"found {bearer.get('bearerFormat')!r}"
            )

    if schema.get("info", {}).get("x-demo-notice") != EXPECTED_NOTICE:
        errors.append("info.x-demo-notice is missing or has drifted from the required notice")

    return errors


def main() -> int:
    """Run the check and report the result."""
    from app.main import create_app

    schema = create_app().openapi()
    errors = collect_errors(schema)

    if errors:
        print("OpenAPI contract check: FAIL", file=sys.stderr)
        for error in errors:
            print(f"  - {error}", file=sys.stderr)
        return 1

    operations = sum(len(methods) for methods in EXPECTED_PATHS.values())
    print(
        "OpenAPI contract check: PASS "
        f"({len(EXPECTED_PATHS)} paths / {operations} operations, "
        f"{len(EXPECTED_SCHEMAS)} schemas)"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
