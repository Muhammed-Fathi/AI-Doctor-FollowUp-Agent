"""Generated OpenAPI checks: the P1 surface must match the accepted P0 contract."""

from __future__ import annotations

from typing import Any

from fastapi.testclient import TestClient

#: Exactly the two public system routes are implemented in P1.
P1_PATHS = {"/health", "/version"}


def _schema() -> dict[str, Any]:
    from app.main import create_app

    return create_app().openapi()


def test_generated_openapi_declares_only_p1_paths() -> None:
    """No speculative P2-P8 endpoint may appear in the P1 schema."""
    assert set(_schema()["paths"]) == P1_PATHS


def test_generated_openapi_is_served(client: TestClient) -> None:
    """``/openapi.json`` is generated by FastAPI, not hand-maintained."""
    response = client.get("/openapi.json")
    assert response.status_code == 200
    assert set(response.json()["paths"]) == P1_PATHS


def test_health_schema_matches_p0_contract() -> None:
    """The generated ``Health`` schema keeps the P0 required set and enums."""
    components = _schema()["components"]["schemas"]

    health = components["Health"]
    assert set(health["required"]) == {"status", "version", "db", "ollama", "tesseract"}
    assert health["properties"]["status"]["enum"] == ["ok", "degraded"]
    # The P0 contract defines DependencyState as a shared component.
    dependency = components["DependencyState"]
    assert dependency["enum"] == ["ok", "unavailable", "not_configured"]


def test_version_schema_matches_p0_contract() -> None:
    """The generated ``VersionInfo`` schema keeps the P0 required set and const."""
    components = _schema()["components"]["schemas"]

    version = components["VersionInfo"]
    assert set(version["required"]) == {
        "app_version",
        "api_version",
        "workflow_version",
        "policy_version",
    }
    assert version["properties"]["api_version"]["const"] == "v1"
    assert version["properties"]["git_sha"]["maxLength"] == 40


def test_openapi_carries_demo_notice() -> None:
    """``REQ-SEC-05``: the educational notice is part of the published schema."""
    schema = _schema()
    assert schema["info"]["x-demo-notice"] == (
        "EDUCATIONAL / SYNTHETIC DATA / NOT FOR CLINICAL USE"
    )


def test_system_operations_are_public() -> None:
    """Both P1 operations are callable without authentication (P0 contract)."""
    schema = _schema()
    for path in P1_PATHS:
        operation = schema["paths"][path]["get"]
        assert operation["security"] == []
