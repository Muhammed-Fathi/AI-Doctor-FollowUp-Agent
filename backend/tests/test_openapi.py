"""Generated OpenAPI checks: the P1 + P2 + P3 surface must match the contract.

The Phase 1 and Phase 2 assertions are kept as they were (P1 paths, P2 paths and
verbs, schemas, public ``security: []``). They are *extended* by an explicit P3
document allowlist rather than relaxed to "at least these paths", so an unplanned
route — including a P4 workflow route — still fails the test, which is the whole
point of the gate.
"""

from __future__ import annotations

from typing import Any

from fastapi.testclient import TestClient

#: Exactly the two public system routes are implemented in P1 (unchanged).
P1_PATHS = {"/health", "/version"}

#: Phase 2 allowlist: 9 paths / 10 operations. ``GET /api/v1/demo/status`` is
#: deliberately absent (``OQ-P2-01``) and ``POST /api/v1/demo/seed`` does not
#: exist in any phase.
P2_PATHS = {
    "/api/v1/auth/login",
    "/api/v1/auth/me",
    "/api/v1/auth/logout",
    "/api/v1/doctor/patients",
    "/api/v1/doctor/patients/{patient_id}",
    "/api/v1/doctor/patients/{patient_id}/timeline",
    "/api/v1/doctor/patients/{patient_id}/observations",
    "/api/v1/patient/check-ins",
    "/api/v1/demo/reset",
}

#: Phase 3 document allowlist: 6 paths / 6 operations. Fixed by
#: ``API_CONTRACT.md`` §2.4; there is no P3 route outside this set.
P3_PATHS = {
    "/api/v1/documents/upload",
    "/api/v1/documents/{document_id}",
    "/api/v1/documents/{document_id}/extraction",
    "/api/v1/documents/{document_id}/text",
    "/api/v1/documents/{document_id}/verify",
    "/api/v1/documents/{document_id}/file",
}

#: Every path the application may expose through P3.
EXPECTED_PATHS = P1_PATHS | P2_PATHS | P3_PATHS

#: Method sets per path: ``/patient/check-ins`` is the one path with two verbs.
EXPECTED_METHODS = {
    "/health": {"get"},
    "/version": {"get"},
    "/api/v1/auth/login": {"post"},
    "/api/v1/auth/me": {"get"},
    "/api/v1/auth/logout": {"post"},
    "/api/v1/doctor/patients": {"get"},
    "/api/v1/doctor/patients/{patient_id}": {"get"},
    "/api/v1/doctor/patients/{patient_id}/timeline": {"get"},
    "/api/v1/doctor/patients/{patient_id}/observations": {"get"},
    "/api/v1/patient/check-ins": {"get", "post"},
    "/api/v1/demo/reset": {"post"},
    # P3 — documents
    "/api/v1/documents/upload": {"post"},
    "/api/v1/documents/{document_id}": {"get"},
    "/api/v1/documents/{document_id}/extraction": {"get"},
    "/api/v1/documents/{document_id}/text": {"get"},
    "/api/v1/documents/{document_id}/verify": {"post"},
    "/api/v1/documents/{document_id}/file": {"get"},
}


def _schema() -> dict[str, Any]:
    from app.main import create_app

    return create_app().openapi()


def test_generated_openapi_declares_only_the_allowlisted_paths() -> None:
    """P1 paths plus the explicit P2 and P3 allowlists; nothing speculative."""
    assert set(_schema()["paths"]) == EXPECTED_PATHS


def test_generated_openapi_declares_the_expected_methods() -> None:
    """Path equality alone is not enough: verbs are asserted per path."""
    paths = _schema()["paths"]

    for path, expected in EXPECTED_METHODS.items():
        assert path in paths, f"{path} is missing"
        found = {method for method in paths[path] if method in EXPECTED_METHODS[path]}
        assert found == expected, f"{path} exposes {sorted(found)}, expected {sorted(expected)}"


def test_no_demo_seed_or_demo_status_route_exists() -> None:
    """``POST /demo/seed`` is not a thing, and ``/demo/status`` waits for P5."""
    paths = set(_schema()["paths"])

    assert "/api/v1/demo/seed" not in paths
    assert "/api/v1/demo/status" not in paths


def test_no_p4_or_later_route_exists() -> None:
    """P4+ surfaces must not appear early, however plausible they look.

    Workflows, review items, tasks, notifications and summaries are later-phase
    deliverables; a route for one of them in P3 would be scope creep that the path
    equality above already rejects. This test names the specific ones so a future
    reader sees the intent, not just a set difference.
    """
    paths = set(_schema()["paths"])

    for forbidden in (
        "/api/v1/workflows/follow-up",
        "/api/v1/review-items",
        "/api/v1/tasks",
        "/api/v1/notifications",
        "/api/v1/summaries",
    ):
        assert forbidden not in paths


def test_generated_openapi_is_served(client: TestClient) -> None:
    """``/openapi.json`` is generated by FastAPI, not hand-maintained."""
    response = client.get("/openapi.json")
    assert response.status_code == 200
    assert set(response.json()["paths"]) == EXPECTED_PATHS


def test_health_schema_matches_p0_contract() -> None:
    """The generated ``Health`` schema keeps the P0 required set and enums."""
    components = _schema()["components"]["schemas"]

    health = components["Health"]
    assert set(health["required"]) == {"status", "version", "db", "ollama", "tesseract"}
    assert health["properties"]["status"]["enum"] == ["ok", "degraded"]
    # The P0 contract defines DependencyState as a shared component.
    dependency = components["DependencyState"]
    assert dependency["enum"] == ["ok", "unavailable", "not_configured"]


def test_version_schema_matches_p0_contract() -> None:
    """The generated ``VersionInfo`` schema keeps the P0 required set and const."""
    components = _schema()["components"]["schemas"]

    version = components["VersionInfo"]
    assert set(version["required"]) == {
        "app_version",
        "api_version",
        "workflow_version",
        "policy_version",
    }
    assert version["properties"]["api_version"]["const"] == "v1"
    assert version["properties"]["git_sha"]["maxLength"] == 40


def test_openapi_carries_demo_notice() -> None:
    """``REQ-SEC-05``: the educational notice is part of the published schema."""
    schema = _schema()
    assert schema["info"]["x-demo-notice"] == (
        "EDUCATIONAL / SYNTHETIC DATA / NOT FOR CLINICAL USE"
    )


def test_system_operations_are_public() -> None:
    """Both P1 operations are callable without authentication (P0 contract)."""
    schema = _schema()
    for path in P1_PATHS:
        operation = schema["paths"][path]["get"]
        assert operation["security"] == []


def test_p2_operations_require_the_bearer_scheme() -> None:
    """Only ``login`` is public in P2; every other operation requires bearerAuth."""
    schema = _schema()

    assert schema["paths"]["/api/v1/auth/login"]["post"]["security"] == []
    for path in sorted(P2_PATHS - {"/api/v1/auth/login"}):
        for method, operation in schema["paths"][path].items():
            if method in {"get", "post"}:
                assert operation["security"] == [{"bearerAuth": []}], f"{method} {path}"


def test_p3_document_operations_require_the_bearer_scheme() -> None:
    """Every P3 document operation is authenticated; none is public.

    Upload is patient-self, extraction/verify are doctor-assigned and the two read
    routes are scope-checked. None of them may be reachable anonymously, so the
    assertion is unconditional over the whole P3 set.
    """
    schema = _schema()

    for path in sorted(P3_PATHS):
        for method, operation in schema["paths"][path].items():
            if method in {"get", "post"}:
                assert operation["security"] == [{"bearerAuth": []}], f"{method} {path}"


def test_p3_document_schemas_are_exactly_the_contract_set() -> None:
    """The ten P3 components are present, and no later-phase schema leaked in."""
    components = set(_schema()["components"]["schemas"])

    assert {
        "DocumentMeta",
        "DocumentPageTextItem",
        "DocumentTextResponse",
        "DocumentUploadResponse",
        "EvidenceRef",
        "ExtractedFact",
        "ExtractionAttemptSummary",
        "ExtractionResponse",
        "VerificationIssue",
        "VerificationRecord",
        "VerifyRequest",
        "VerifyResponse",
    } <= components

    # P4/P5 deliverable shapes must not exist yet.
    assert {
        "DraftSummary",
        "WorkflowRun",
        "ReviewItem",
        "ApprovalDecision",
        "FollowUpTask",
        "Notification",
    }.isdisjoint(components)


def test_verification_issue_schema_has_no_rule_id() -> None:
    """``VI-*`` issues are a different output type from ``DR-*`` review items.

    The contract is explicit that a verification issue never carries a
    ``rule_id``; a shared shape would let the two blend in the UI.
    """
    components = _schema()["components"]["schemas"]
    issue = components["VerificationIssue"]

    assert "rule_id" not in issue["properties"]
    # ``issue_type`` is a $ref to the IssueType component, so the enum lives
    # there rather than inline.
    assert set(components["IssueType"]["enum"]) == {
        "VI-001",
        "VI-002",
        "VI-003",
        "VI-004",
        "VI-005",
        "VI-006",
    }
    assert issue["properties"]["blocking"]["const"] is True
    assert issue["required"] == [
        "issue_id",
        "issue_type",
        "reason_code",
        "blocking",
        "message",
        "evidence",
        "created_at",
    ]


def test_bearer_scheme_matches_the_p0_contract() -> None:
    """The scheme is the contract's opaque HTTP bearer token."""
    scheme = _schema()["components"]["securitySchemes"]["bearerAuth"]

    assert scheme["type"] == "http"
    assert scheme["scheme"] == "bearer"
    assert scheme["bearerFormat"] == "opaque-session-token"
