"""Generated OpenAPI checks: the P1 + P2 surface must match the accepted contract.

The Phase 1 assertions are kept as they were (P1 paths, schemas, public
``security: []``). They are *extended* by an explicit P2 allowlist rather than
relaxed to "at least these paths", so an unplanned route still fails the test —
which is the whole point of the gate.
"""

from __future__ import annotations

from typing import Any

from fastapi.testclient import TestClient

#: Exactly the two public system routes are implemented in P1 (unchanged).
P1_PATHS = {"/health", "/version"}

#: Phase 2 allowlist: 9 paths / 10 operations. ``GET /api/v1/demo/status`` is
#: deliberately absent (``OQ-P2-01``) and ``POST /api/v1/demo/seed`` does not
#: exist in any phase.
P2_PATHS = {
    "/api/v1/auth/login",
    "/api/v1/auth/me",
    "/api/v1/auth/logout",
    "/api/v1/doctor/patients",
    "/api/v1/doctor/patients/{patient_id}",
    "/api/v1/doctor/patients/{patient_id}/timeline",
    "/api/v1/doctor/patients/{patient_id}/observations",
    "/api/v1/patient/check-ins",
    "/api/v1/demo/reset",
}

#: Every path the application may expose in P2.
EXPECTED_PATHS = P1_PATHS | P2_PATHS

#: Method sets per path: ``/patient/check-ins`` is the one path with two verbs.
EXPECTED_METHODS = {
    "/health": {"get"},
    "/version": {"get"},
    "/api/v1/auth/login": {"post"},
    "/api/v1/auth/me": {"get"},
    "/api/v1/auth/logout": {"post"},
    "/api/v1/doctor/patients": {"get"},
    "/api/v1/doctor/patients/{patient_id}": {"get"},
    "/api/v1/doctor/patients/{patient_id}/timeline": {"get"},
    "/api/v1/doctor/patients/{patient_id}/observations": {"get"},
    "/api/v1/patient/check-ins": {"get", "post"},
    "/api/v1/demo/reset": {"post"},
}


def _schema() -> dict[str, Any]:
    from app.main import create_app

    return create_app().openapi()


def test_generated_openapi_declares_only_the_allowlisted_paths() -> None:
    """P1 paths plus the explicit P2 allowlist; nothing speculative."""
    assert set(_schema()["paths"]) == EXPECTED_PATHS


def test_generated_openapi_declares_the_expected_methods() -> None:
    """Path equality alone is not enough: verbs are asserted per path."""
    paths = _schema()["paths"]

    for path, expected in EXPECTED_METHODS.items():
        assert path in paths, f"{path} is missing"
        found = {method for method in paths[path] if method in EXPECTED_METHODS[path]}
        assert found == expected, f"{path} exposes {sorted(found)}, expected {sorted(expected)}"


def test_no_demo_seed_or_demo_status_route_exists() -> None:
    """``POST /demo/seed`` is not a thing, and ``/demo/status`` waits for P5."""
    paths = set(_schema()["paths"])

    assert "/api/v1/demo/seed" not in paths
    assert "/api/v1/demo/status" not in paths


def test_generated_openapi_is_served(client: TestClient) -> None:
    """``/openapi.json`` is generated by FastAPI, not hand-maintained."""
    response = client.get("/openapi.json")
    assert response.status_code == 200
    assert set(response.json()["paths"]) == EXPECTED_PATHS


def test_health_schema_matches_p0_contract() -> None:
    """The generated ``Health`` schema keeps the P0 required set and enums."""
    components = _schema()["components"]["schemas"]

    health = components["Health"]
    assert set(health["required"]) == {"status", "version", "db", "ollama", "tesseract"}
    assert health["properties"]["status"]["enum"] == ["ok", "degraded"]
    # The P0 contract defines DependencyState as a shared component.
    dependency = components["DependencyState"]
    assert dependency["enum"] == ["ok", "unavailable", "not_configured"]


def test_version_schema_matches_p0_contract() -> None:
    """The generated ``VersionInfo`` schema keeps the P0 required set and const."""
    components = _schema()["components"]["schemas"]

    version = components["VersionInfo"]
    assert set(version["required"]) == {
        "app_version",
        "api_version",
        "workflow_version",
        "policy_version",
    }
    assert version["properties"]["api_version"]["const"] == "v1"
    assert version["properties"]["git_sha"]["maxLength"] == 40


def test_openapi_carries_demo_notice() -> None:
    """``REQ-SEC-05``: the educational notice is part of the published schema."""
    schema = _schema()
    assert schema["info"]["x-demo-notice"] == (
        "EDUCATIONAL / SYNTHETIC DATA / NOT FOR CLINICAL USE"
    )


def test_system_operations_are_public() -> None:
    """Both P1 operations are callable without authentication (P0 contract)."""
    schema = _schema()
    for path in P1_PATHS:
        operation = schema["paths"][path]["get"]
        assert operation["security"] == []


def test_p2_operations_require_the_bearer_scheme() -> None:
    """Only ``login`` is public in P2; every other operation requires bearerAuth."""
    schema = _schema()

    assert schema["paths"]["/api/v1/auth/login"]["post"]["security"] == []
    for path in sorted(P2_PATHS - {"/api/v1/auth/login"}):
        for method, operation in schema["paths"][path].items():
            if method in {"get", "post"}:
                assert operation["security"] == [{"bearerAuth": []}], f"{method} {path}"


def test_bearer_scheme_matches_the_p0_contract() -> None:
    """The scheme is the contract's opaque HTTP bearer token."""
    scheme = _schema()["components"]["securitySchemes"]["bearerAuth"]

    assert scheme["type"] == "http"
    assert scheme["scheme"] == "bearer"
    assert scheme["bearerFormat"] == "opaque-session-token"
