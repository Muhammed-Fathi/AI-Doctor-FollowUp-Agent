"""FastAPI application factory.

Phase 1 contributed ``GET /health`` and ``GET /version`` (``MASTER_PLAN.md`` §5
P1). Phase 2 adds the patient-domain surface under ``/api/v1`` (auth, doctor
reads, patient check-ins and the demo reset), assembled in
``app.api.v1.router``. ``/openapi.json`` is generated by FastAPI itself.

The factory keeps the module import side-effect free, so tests can build an app
against a temporary SQLite database without touching ``data/runtime``.
"""

from __future__ import annotations

from fastapi import FastAPI

from app.api import system
from app.api.v1.router import router as v1_router
from app.core.config import Settings, get_settings
from app.core.errors import install_problem_handlers
from app.core.logging import configure_logging
from app.core.version import (
    API_VERSION,
    APP_VERSION,
    DEMO_NOTICE,
    POLICY_VERSION,
    WORKFLOW_VERSION,
)

DESCRIPTION = """
Local, synthetic-data, single-machine academic demo.

**EDUCATIONAL / SYNTHETIC DATA / NOT FOR CLINICAL USE.**

Phase 2 (patient domain and role-based API) exposes `/health`, `/version` and
the `/api/v1` authentication, doctor, patient check-in and demo-reset routes.
There is still no document extraction, OCR, monitoring, agent workflow or
follow-up task endpoint: `documents`, `review_items` and `tasks` are returned as
empty arrays wherever the contract mentions them.
""".strip()


def create_app(settings: Settings | None = None) -> FastAPI:
    """Build the ASGI application.

    Args:
        settings: Optional explicit settings; defaults to the cached settings
            from the environment / ``.env``.
    """
    resolved = settings or get_settings()
    configure_logging(resolved.log_level)

    app = FastAPI(
        title="AI Doctor Follow-Up — Backend (P2 patient domain)",
        summary="EDUCATIONAL / SYNTHETIC DATA / NOT FOR CLINICAL USE",
        description=DESCRIPTION,
        version=APP_VERSION,
        docs_url="/docs",
        redoc_url=None,
        openapi_url="/openapi.json",
        openapi_tags=[
            {"name": "system", "description": "Liveness and version metadata (public)."},
            {"name": "auth", "description": "Local demo login, identity and logout."},
            {"name": "doctor", "description": "Assignment-scoped patient reads."},
            {"name": "patient", "description": "Self-scoped check-ins."},
            {"name": "demo", "description": "Admin-only synthetic dataset reset."},
        ],
    )

    # Problem+json error envelopes, request-id middleware and 401/403/404/409
    # bodies all come from one place so no route hand-rolls its own error shape.
    install_problem_handlers(app)

    app.include_router(system.router)
    app.include_router(v1_router)

    # Contract metadata for the published OpenAPI document: the educational
    # notice (REQ-SEC-05) and the contract versions, so a generated client can
    # detect the schema generation it is talking to.
    base_openapi = app.openapi

    def _openapi_with_notice() -> dict[str, object]:
        schema = base_openapi()
        info = schema.setdefault("info", {})
        info["x-demo-notice"] = DEMO_NOTICE
        info["x-design-status"] = "P2_PATIENT_DOMAIN"
        info["x-api-version"] = API_VERSION
        info["x-workflow-version"] = WORKFLOW_VERSION
        info["x-policy-version"] = POLICY_VERSION

        # ``openapi.phase0.yaml`` declares a global ``bearerAuth`` requirement
        # (overridden with ``security: []`` on the public operations) and gives
        # the scheme a ``bearerFormat``. FastAPI emits the scheme from the
        # ``HTTPBearer`` dependency but leaves both details to the app, so they
        # are completed here — one place, asserted by the OpenAPI gate.
        components = schema.setdefault("components", {})
        schemes = components.setdefault("securitySchemes", {})
        bearer = schemes.setdefault("bearerAuth", {})
        bearer.update(
            {
                "type": "http",
                "scheme": "bearer",
                "bearerFormat": "opaque-session-token",
                "description": "Local demo session token; roles doctor, patient, demo_admin.",
            }
        )
        schema["security"] = [{"bearerAuth": []}]
        return schema

    app.openapi = _openapi_with_notice  # type: ignore[method-assign]

    return app


#: Module-level app for ``uvicorn app.main:app``.
app = create_app()


__all__ = ["app", "create_app"]
