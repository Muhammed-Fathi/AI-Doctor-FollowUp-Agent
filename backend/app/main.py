"""FastAPI application factory.

Phase 1 exposes exactly two routes: ``GET /health`` and ``GET /version``
(``MASTER_PLAN.md`` §5 P1). ``/openapi.json`` is generated by FastAPI itself.

The factory keeps the module import side-effect free, so tests can build an app
against a temporary SQLite database without touching ``data/runtime``.
"""

from __future__ import annotations

from fastapi import FastAPI

from app.api import system
from app.core.config import Settings, get_settings
from app.core.logging import configure_logging
from app.core.version import (
    API_VERSION,
    APP_VERSION,
    DEMO_NOTICE,
    POLICY_VERSION,
    WORKFLOW_VERSION,
)

DESCRIPTION = """
Local, synthetic-data, single-machine academic demo.

**EDUCATIONAL / SYNTHETIC DATA / NOT FOR CLINICAL USE.**

Phase 1 (foundation) exposes only `/health` and `/version`. No patient data,
authentication, document extraction, OCR, monitoring, agent workflow or
follow-up task endpoint exists yet.
""".strip()


def create_app(settings: Settings | None = None) -> FastAPI:
    """Build the ASGI application.

    Args:
        settings: Optional explicit settings; defaults to the cached settings
            from the environment / ``.env``.
    """
    resolved = settings or get_settings()
    configure_logging(resolved.log_level)

    app = FastAPI(
        title="AI Doctor Follow-Up — Backend (P1 foundation)",
        summary="EDUCATIONAL / SYNTHETIC DATA / NOT FOR CLINICAL USE",
        description=DESCRIPTION,
        version=APP_VERSION,
        docs_url="/docs",
        redoc_url=None,
        openapi_url="/openapi.json",
        openapi_tags=[{"name": "system", "description": "Liveness and version metadata (public)."}],
    )

    app.include_router(system.router)

    # Contract metadata for the published OpenAPI document: the educational
    # notice (REQ-SEC-05) and the contract versions, so a generated client can
    # detect the schema generation it is talking to.
    base_openapi = app.openapi

    def _openapi_with_notice() -> dict[str, object]:
        schema = base_openapi()
        info = schema.setdefault("info", {})
        info["x-demo-notice"] = DEMO_NOTICE
        info["x-design-status"] = "P1_FOUNDATION"
        info["x-api-version"] = API_VERSION
        info["x-workflow-version"] = WORKFLOW_VERSION
        info["x-policy-version"] = POLICY_VERSION
        return schema

    app.openapi = _openapi_with_notice  # type: ignore[method-assign]

    return app


#: Module-level app for ``uvicorn app.main:app``.
app = create_app()


__all__ = ["app", "create_app"]
